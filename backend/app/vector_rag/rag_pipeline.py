class FactCheckingRAGPipeline:
    """
    End-to-End RAG Verification Architecture:
    1. Dense Embedding Generation
    2. Vector Search (FAISS IndexFlatIP & Qdrant Engine)
    3. Hybrid Lexical-Dense Reranking (RRF & Cross-Scoring)
    4. Verified Synthesis & Source Attribution
    5. Automatic RAGAS & DeepEval Evaluation Metrics
    """
    def __init__(self, primary_engine: str = "faiss"):
        self.primary_engine_type = primary_engine
        self.embedding_engine = embedding_engine
        self.reranker = reranker_engine
        self.evaluator = rag_evaluator
        
        # Initialize both vector stores for benchmarking and multi-engine support
        self.faiss_store = FAISSVectorIndex(embedding_dim=384)
        self.qdrant_store = QdrantVectorIndex(collection_name="misinfo_factcheck", embedding_dim=384)
        
        self._ingest_initial_corpus()

    def _ingest_initial_corpus(self):
        """Encodes and indexes the initial ground-truth fact-check knowledge base."""
        logger.info(f"Ingesting {len(INITIAL_KNOWLEDGE_CORPUS)} fact-checking documents into Vector DBs...")
        texts = [doc["text"] for doc in INITIAL_KNOWLEDGE_CORPUS]
        embeddings = self.embedding_engine.embed_batch(texts)
        
        # Populate FAISS
        self.faiss_store.add_documents(INITIAL_KNOWLEDGE_CORPUS, embeddings)
        
        # Populate Qdrant
        self.qdrant_store.add_documents(INITIAL_KNOWLEDGE_CORPUS, embeddings)
        logger.info("Vector DBs successfully populated with FAISS & Qdrant indices.")

    def add_custom_document(self, title: str, text: str, category: str, source: str, verdict: str) -> Dict[str, Any]:
        """Dynamically ingests a new ground-truth fact-check into both FAISS and Qdrant."""
        doc_id = f"custom_{self.faiss_store.count() + 1}"
        doc = {
            "id": doc_id,
            "title": title,
            "text": text,
            "category": category,
            "source": source,
            "verdict": verdict,
            "ground_truth": text
        }
        emb = self.embedding_engine.embed_text(text).reshape(1, -1)
        self.faiss_store.add_documents([doc], emb)
        self.qdrant_store.add_documents([doc], emb)
        return {"success": True, "doc_id": doc_id, "total_docs": self.faiss_store.count()}

    def retrieve(self, query: str, top_k: int = 4, engine: Optional[str] = None) -> List[Dict[str, Any]]:
        """Dense semantic retrieval from selected vector store."""
        target_engine = engine or self.primary_engine_type
        query_vector = self.embedding_engine.embed_text(query)
        
        if "qdrant" in target_engine.lower():
            return self.qdrant_store.search(query_vector, top_k=top_k)
        return self.faiss_store.search(query_vector, top_k=top_k)

    def verify_claim(self, claim_text: str, top_k: int = 3, vector_engine: str = "faiss") -> Dict[str, Any]:
        """
        Full RAG Verification Workflow:
        Query -> Dense Vector Retrieval -> Reranker -> Synthesized Fact-Check -> RAGAS/DeepEval Evaluation.
        """
        # 1. First-Stage Retrieval (Fetch top-6 candidate passages)
        raw_candidates = self.retrieve(claim_text, top_k=6, engine=vector_engine)
        
        if not raw_candidates:
            return {
                "success": False,
                "error": "Vector database contains no matching knowledge records."
            }

        # 2. Second-Stage Reranking (RRF & Cross-Scoring to top_k)
        reranked_docs = self.reranker.rerank(claim_text, raw_candidates, top_k=top_k)
        top_doc = reranked_docs[0] if reranked_docs else raw_candidates[0]

        # 3. Fact Synthesis & Grounded Verdict Formulation
        best_similarity = top_doc.get("rerank_score", top_doc.get("similarity_score", 0.0))
        
        if best_similarity >= 0.15:
            verdict = top_doc.get("verdict", "UNVERIFIED")
            synthesis = (
                f"Verdict: {verdict}. {top_doc.get('text')} [Verified by {top_doc.get('source')}]."
            )
            ground_truth_ref = top_doc.get("text", "")
            confidence = round(min(0.99, max(0.60, best_similarity * 2.5)), 4)
        elif best_similarity >= 0.08:
            verdict = "INSUFFICIENT_EVIDENCE / UNVERIFIED"
            synthesis = (
                f"Verdict: {verdict}. Contextual records from {top_doc.get('source')} "
                f"do not conclusively substantiate the assertions in '{claim_text}'."
            )
            ground_truth_ref = top_doc.get("text", "")
            confidence = round(best_similarity, 4)
        else:
            verdict = "NO_RECORD_FOUND"
            synthesis = "No high-confidence verified fact-checks match this specific claim in the vector index."
            ground_truth_ref = ""
            confidence = 0.25

        # 4. Compute Comprehensive RAGAS & DeepEval Metric Scores
        eval_metrics = self.evaluator.evaluate_all(
            query=claim_text,
            generated_answer=synthesis,
            retrieved_docs=reranked_docs,
            ground_truth=ground_truth_ref
        )

        return {
            "success": True,
            "claim": claim_text,
            "verdict": verdict,
            "confidence": confidence,
            "synthesized_response": synthesis,
            "vector_engine_used": top_doc.get("engine", vector_engine.upper()),
            "retrieved_and_reranked_sources": reranked_docs,
            "ragas_metrics": eval_metrics["ragas_scores"],
            "deepeval_metrics": eval_metrics["deepeval_scores"],
            "composite_rag_score": eval_metrics["composite_rag_score"],
            "reliability_status": eval_metrics["verdict"],
            "unsupported_assertions": eval_metrics["unsupported_assertions"]
        }

